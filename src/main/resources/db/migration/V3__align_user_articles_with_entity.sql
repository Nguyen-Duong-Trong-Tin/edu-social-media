ALTER TABLE user_articles ALTER COLUMN status DROP DEFAULT;

ALTER TABLE user_articles DROP COLUMN name, DROP COLUMN slug, DROP COLUMN description;

CREATE TABLE user_article_files (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    type character varying(255) NOT NULL CHECK (type IN ('IMAGE', 'VIDEO')),
    path text,
    user_article_id bigint NOT NULL REFERENCES user_articles (id)
);

CREATE INDEX idx_user_article_files_article ON user_article_files (user_article_id);
